func renderInboxHandler(name string, module string) ([]byte, error) {
	var source strings.Builder
	source.WriteString(
		"// Package handler owns one transaction-local Inbox behavior.\n" +
			"package handler\n\n" +
			"import (\n" +
			"\t\"context\"\n" +
			"\t\"database/sql\"\n" +
			"\t\"errors\"\n\n" +
			"\t\"github.com/keelab/keelith/worker\"\n",
	)
	fmt.Fprintf(
		&source,
		"\tapplicationdependency %q\n",
		module+"/internal/dependency",
	)
	source.WriteString(")\n\n")
	fmt.Fprintf(
		&source,
		"// ErrNotImplemented prevents %s deliveries from being acknowledged.\n"+
			"var ErrNotImplemented = errors.New(%q)\n\n",
		name,
		"inbox "+name+": transactional handler is not implemented",
	)
	source.WriteString(
		"// Handler owns explicit application dependencies for one Inbox behavior.\n" +
			"type Handler struct {\n" +
			"\tDependencies *applicationdependency.Clients\n" +
			"}\n\n" +
			"// New validates and injects application-scoped dependency clients.\n" +
			"func New(dependencies *applicationdependency.Clients) (*Handler, error) {\n" +
			"\tif dependencies == nil {\n" +
			"\t\treturn nil, errors.New(\"inbox handler: dependency clients are nil\")\n" +
			"\t}\n" +
			"\treturn &Handler{Dependencies: dependencies}, nil\n" +
			"}\n\n" +
			"// Handle applies business SQL using the Inbox-owned transaction.\n" +
			"func (_ *Handler) Handle(\n" +
			"\t_ context.Context,\n" +
			"\t_ *sql.Tx,\n" +
			"\t_ worker.Message,\n" +
			") worker.Result {\n" +
			"\treturn worker.Nack(ErrNotImplemented)\n" +
			"}\n",
	)
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf(
			"scaffold: format Inbox handler: %w",
			err,
		)
	}
	return formatted, nil
}

