func normalizeSQLDriver(value string) (
	dialect string,
	driver string,
	defaultSystem string,
	ok bool,
) {
	switch strings.ToLower(strings.TrimSpace(value)) {
	case "mysql":
		return "mysql", "mysql", "mysql", true
	case "postgres", "postgresql", "pgx":
		return "postgres", "pgx", "postgresql", true
	default:
		return "", "", "", false
	}
}

// componentSQLDialect preserves v35 declarations, where SQL manifests did
// not yet carry an explicit dialect. Those declarations only generated the
// MySQL driver and therefore remain MySQL.
func componentSQLDialect(manifest componentManifest) string {
	if manifest.Kind != "sql" {
		return ""
	}
	if manifest.Driver == "" {
		return "mysql"
	}
	return manifest.Driver
}

func declaredComponent(
	ctx context.Context,
	project string,
	name string,
	kind string,
) (componentManifest, error) {
	components, err := readComponentManifests(ctx, project)
	if err != nil {
		return componentManifest{}, err
	}
	for _, component := range components {
		if component.manifest.Name == name {
			if component.manifest.Kind != kind {
				break
			}
			return component.manifest, nil
		}
	}
	return componentManifest{}, fmt.Errorf(
		"%w: component %q must reference declared %s %q",
		ErrConflict,
		name,
		kind,
		name,
	)
}

