// AddJobOwnershipComponent creates one Redis- or Kubernetes-backed renewable
// ownership declaration for a declared local Cron Job.
func AddJobOwnershipComponent(
	ctx context.Context,
	options AddJobOwnershipComponentOptions,
) (AddComponentResult, error) {
	if ctx == nil {
		return AddComponentResult{}, fmt.Errorf(
			"%w: context is nil",
			ErrInvalidInput,
		)
	}
	if cause := context.Cause(ctx); cause != nil {
		return AddComponentResult{}, cause
	}
	project, err := resolveComponentProject(options.Project)
	if err != nil {
		return AddComponentResult{}, err
	}
	options.Name = strings.TrimSpace(options.Name)
	options.Service = strings.TrimSpace(options.Service)
	options.Provider = strings.ToLower(strings.TrimSpace(options.Provider))
	options.CronJob = strings.TrimSpace(options.CronJob)
	options.Redis = strings.TrimSpace(options.Redis)
	options.Namespace = strings.TrimSpace(options.Namespace)
	options.LeaseName = strings.TrimSpace(options.LeaseName)
	if options.Provider == "" {
		options.Provider = "redis"
	}
	if !validComponentName(options.Name) ||
		!validComponentName(options.CronJob) {
		return AddComponentResult{}, fmt.Errorf(
			"%w: component name or reference is invalid",
			ErrInvalidInput,
		)
	}
	if options.LeaseTTL == 0 {
		options.LeaseTTL = 30 * time.Second
	}
	config := jobOwnershipYAMLConfig{
		Key: options.Key,
		TTL: options.LeaseTTL,
	}
	files := make([]applicationComponentFile, 0, 8)
	switch options.Provider {
	case "redis":
		if !validComponentName(options.Redis) ||
			options.Service != "" ||
			options.Namespace != "" ||
			options.LeaseName != "" {
			return AddComponentResult{}, fmt.Errorf(
				"%w: Redis ownership requires only a Redis reference",
				ErrInvalidInput,
			)
		}
		if options.CoordinationPrefix == "" {
			options.CoordinationPrefix = "keelith:lease:"
		}
		runtimeConfig := jobOwnershipYAMLConfig{
			Key:    options.Key,
			TTL:    options.LeaseTTL,
			Prefix: options.CoordinationPrefix,
		}
		if err := validateRedisJobOwnershipConfig(runtimeConfig); err != nil {
			return AddComponentResult{}, fmt.Errorf(
				"%w: Job ownership component: %w",
				ErrInvalidInput,
				err,
			)
		}
		config.Prefix = runtimeConfig.Prefix
	case "kubernetes":
		if !validComponentName(options.Service) ||
			options.Redis != "" ||
			options.CoordinationPrefix != "" {
			return AddComponentResult{}, fmt.Errorf(
				"%w: Kubernetes ownership requires service, namespace, and Lease name",
				ErrInvalidInput,
			)
		}
		runtimeConfig := jobOwnershipYAMLConfig{
			Key:       options.Key,
			TTL:       options.LeaseTTL,
			Namespace: options.Namespace,
			LeaseName: options.LeaseName,
		}
		if err := validateKubernetesJobOwnershipConfig(runtimeConfig); err != nil {
			return AddComponentResult{}, fmt.Errorf(
				"%w: Job ownership component: %w",
				ErrInvalidInput,
				err,
			)
		}
		config.Namespace = runtimeConfig.Namespace
		config.LeaseName = runtimeConfig.LeaseName
		files = append(
			files,
			renderKubernetesJobOwnershipFiles(options)...,
		)
	default:
		return AddComponentResult{}, fmt.Errorf(
			"%w: Job ownership provider must be redis or kubernetes",
			ErrInvalidInput,
		)
	}
	configRelative := "config/components/" + options.Name + ".yaml"
	manifest := componentManifest{
		SchemaVersion: componentManifestVersion,
		Kind:          "job-ownership",
		Name:          options.Name,
		Config:        configRelative,
		Driver:        options.Provider,
		CronJob:       options.CronJob,
	}
	if options.Provider == "redis" {
		manifest.Redis = options.Redis
	}
	declaration, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return AddComponentResult{}, fmt.Errorf(
			"scaffold: encode component declaration: %w",
			err,
		)
	}
	declaration = append(declaration, '\n')
	document := jobOwnershipComponentDocument{}
	document.Components.Jobs.Ownership = map[string]jobOwnershipYAMLConfig{
		options.Name: config,
	}
	configuration, err := yaml.Marshal(document)
	if err != nil {
		return AddComponentResult{}, fmt.Errorf(
			"scaffold: encode component config: %w",
			err,
		)
	}
	files = append(
		[]applicationComponentFile{
			{
				relative: ".keelith/components/" + options.Name + ".json",
				content:  declaration,
			},
			{relative: configRelative, content: configuration},
		},
		files...,
	)
	return writeApplicationComponentFiles(
		ctx,
		project,
		files,
	)
}

