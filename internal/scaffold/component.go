func writeApplicationComponentFiles(
	ctx context.Context,
	project string,
	files []applicationComponentFile,
) (AddComponentResult, error) {
	result := AddComponentResult{Project: project}
	type pendingFile struct {
		path     string
		relative string
		content  []byte
	}
	pending := make([]pendingFile, 0, len(files))
	for _, file := range files {
		if cause := context.Cause(ctx); cause != nil {
			return AddComponentResult{}, cause
		}
		output, pathErr := safeAddOutputPath(project, file.relative, true)
		if pathErr != nil {
			return AddComponentResult{}, pathErr
		}
		existing, exists, readErr := readRegularComponentFile(
			output,
			file.relative,
		)
		if readErr != nil {
			return AddComponentResult{}, readErr
		}
		if exists {
			if file.preserveExisting {
				result.Unchanged = append(result.Unchanged, file.relative)
				continue
			}
			if !bytes.Equal(existing, file.content) {
				return AddComponentResult{}, fmt.Errorf(
					"%w: %s already exists with different content",
					ErrConflict,
					file.relative,
				)
			}
			result.Unchanged = append(result.Unchanged, file.relative)
			continue
		}
		pending = append(pending, pendingFile{
			path:     output,
			relative: file.relative,
			content:  file.content,
		})
	}
	createdPaths := make([]string, 0, len(pending))
	rollback := func(cause error) (AddComponentResult, error) {
		failures := []error{cause}
		for index := len(createdPaths) - 1; index >= 0; index-- {
			if removeErr := os.Remove(createdPaths[index]); removeErr != nil &&
				!errors.Is(removeErr, os.ErrNotExist) {
				failures = append(failures, removeErr)
			}
		}
		return AddComponentResult{}, errors.Join(failures...)
	}
	for _, file := range pending {
		if cause := context.Cause(ctx); cause != nil {
			return rollback(cause)
		}
		if err := os.MkdirAll(filepath.Dir(file.path), 0o755); err != nil {
			return rollback(fmt.Errorf(
				"scaffold: create %s directory: %w",
				file.relative,
				err,
			))
		}
		if err := createExclusiveFile(file.path, file.content); err != nil {
			return rollback(fmt.Errorf(
				"%w: create %s: %w",
				ErrConflict,
				file.relative,
				err,
			))
		}
		createdPaths = append(createdPaths, file.path)
		result.Created = append(result.Created, file.relative)
	}
	sort.Strings(result.Created)
	sort.Strings(result.Unchanged)
	return result, nil
}

// SyncComponents validates application component declarations and rewrites the
// single Keelith-owned typed registry.
func SyncComponents(
	ctx context.Context,
	project string,
	module string,
) (SyncComponentsResult, error) {
	if ctx == nil {
		return SyncComponentsResult{}, fmt.Errorf(
			"%w: context is nil",
			ErrInvalidInput,
		)
	}
	if cause := context.Cause(ctx); cause != nil {
		return SyncComponentsResult{}, cause
	}
	root, err := resolveComponentProject(project)
	if err != nil {
		return SyncComponentsResult{}, err
	}
	module = strings.TrimSpace(module)
	if err := validateModule(module); err != nil {
		return SyncComponentsResult{}, err
	}
	components, err := readComponentManifests(ctx, root)
	if err != nil {
		return SyncComponentsResult{}, err
	}
	componentContent, err := renderComponentRegistry(components)
	if err != nil {
		return SyncComponentsResult{}, err
	}
	componentRelative := "internal/component/zz_keelith_components.gen.go"
	componentOutput, err := safeAddOutputPath(
		root,
		componentRelative,
		true,
	)
	if err != nil {
		return SyncComponentsResult{}, err
	}
	componentBefore, componentExists, err := readManagedRegistration(
		componentOutput,
		componentRelative,
	)
	if err != nil {
		return SyncComponentsResult{}, err
	}
	outputs := []managedBindingOutput{{
		path:     componentOutput,
		relative: componentRelative,
		content:  componentContent,
		before:   componentBefore,
		exists:   componentExists,
	}}
	hasConsumer := false
	for _, component := range components {
		if component.manifest.Kind == "kafka-consumer" {
			hasConsumer = true
			break
		}
	}
	if hasConsumer {
		consumerContent, renderErr := renderConsumerRegistry(
			components,
			module,
		)
		if renderErr != nil {
			return SyncComponentsResult{}, renderErr
		}
		consumerRelative :=
			"internal/consumer/zz_keelith_consumers.gen.go"
		consumerOutput, pathErr := safeAddOutputPath(
			root,
			consumerRelative,
			true,
		)
		if pathErr != nil {
			return SyncComponentsResult{}, pathErr
		}
		consumerBefore, consumerExists, readErr :=
			readManagedRegistration(consumerOutput, consumerRelative)
		if readErr != nil {
			return SyncComponentsResult{}, readErr
		}
		outputs = append(outputs, managedBindingOutput{
			path:     consumerOutput,
			relative: consumerRelative,
			content:  consumerContent,
			before:   consumerBefore,
			exists:   consumerExists,
		})
	}
	hasCronJob := false
	for _, component := range components {
		if component.manifest.Kind == "cron-job" {
			hasCronJob = true
			break
		}
	}
	if hasCronJob {
		jobContent, renderErr := renderJobRegistry(components, module)
		if renderErr != nil {
			return SyncComponentsResult{}, renderErr
		}
		jobRelative := "internal/job/zz_keelith_jobs.gen.go"
		jobOutput, pathErr := safeAddOutputPath(
			root,
			jobRelative,
			true,
		)
		if pathErr != nil {
			return SyncComponentsResult{}, pathErr
		}
		jobBefore, jobExists, readErr :=
			readManagedRegistration(jobOutput, jobRelative)
		if readErr != nil {
			return SyncComponentsResult{}, readErr
		}
		outputs = append(outputs, managedBindingOutput{
			path:     jobOutput,
			relative: jobRelative,
			content:  jobContent,
			before:   jobBefore,
			exists:   jobExists,
		})
	}
	kubernetesRelative := "config/components/kustomization.yaml"
	kubernetesOutput, err := safeAddOutputPath(
		root,
		kubernetesRelative,
		true,
	)
	if err != nil {
		return SyncComponentsResult{}, err
	}
	kubernetesBefore, kubernetesExists, err := readRegularComponentFile(
		kubernetesOutput,
		kubernetesRelative,
	)
	if err != nil {
		return SyncComponentsResult{}, err
	}
	if kubernetesExists {
		if !bytes.HasPrefix(
			kubernetesBefore,
			[]byte(kubernetesComponentHeader+"\n"),
		) {
			return SyncComponentsResult{}, fmt.Errorf(
				"%w: %s is not managed by Keelith",
				ErrConflict,
				kubernetesRelative,
			)
		}
		kubernetesContent := renderKubernetesComponentConfig(components)
		outputs = append(outputs, managedBindingOutput{
			path:     kubernetesOutput,
			relative: kubernetesRelative,
			content:  kubernetesContent,
			before:   kubernetesBefore,
			exists:   true,
		})
	}
	managed, err := writeManagedBindingOutputs(outputs)
	if err != nil {
		return SyncComponentsResult{}, err
	}
	return SyncComponentsResult{
		Project:    root,
		Components: len(components),
		Created:    managed.created,
		Updated:    managed.updated,
		Unchanged:  managed.unchanged,
	}, nil
}

func renderKubernetesComponentConfig(
	components []applicationComponent,
) []byte {
	var document strings.Builder
	document.WriteString(
		kubernetesComponentHeader + "\n" +
			"apiVersion: kustomize.config.k8s.io/v1alpha1\n" +
			"kind: Component\n\n" +
			"configMapGenerator:\n" +
			"  - name: keelith-application-components\n" +
			"    files:\n" +
			"      - placeholder.yaml\n",
	)
	for _, component := range components {
		fmt.Fprintf(
			&document,
			"      - %s\n",
			filepath.Base(component.manifest.Config),
		)
	}
	return []byte(document.String())
}

func resolveComponentProject(project string) (string, error) {
	root, err := filepath.Abs(strings.TrimSpace(project))
	if err != nil {
		return "", fmt.Errorf("%w: project path: %w", ErrInvalidInput, err)
	}
	root, err = filepath.EvalSymlinks(root)
	if err != nil {
		return "", fmt.Errorf(
			"%w: resolve project symlinks: %w",
			ErrInvalidInput,
			err,
		)
	}
	info, err := os.Stat(root)
	if err != nil || !info.IsDir() {
		return "", fmt.Errorf("%w: project is not a directory", ErrInvalidInput)
	}
	return root, nil
}

func componentProjectModule(project string) (string, error) {
	identity, err := projectinfo.Load(project)
	if err != nil {
		return "", fmt.Errorf("scaffold: read Go project: %w", err)
	}
	if err := validateModule(identity.Module); err != nil {
		return "", err
	}
	return identity.Module, nil
}

func validComponentName(name string) bool {
	return len(name) <= 63 && componentNamePattern.MatchString(name)
}

func readRegularComponentFile(
	path string,
	relative string,
) ([]byte, bool, error) {
	info, err := os.Lstat(path)
	switch {
	case errors.Is(err, os.ErrNotExist):
		return nil, false, nil
	case err != nil:
		return nil, false, fmt.Errorf(
			"scaffold: inspect %s: %w",
			relative,
			err,
		)
	case info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular():
		return nil, false, fmt.Errorf(
			"%w: %s is not a regular file",
			ErrConflict,
			relative,
		)
	case info.Size() > maxComponentConfigBytes:
		return nil, false, fmt.Errorf(
			"%w: %s exceeds %d bytes",
			ErrConflict,
			relative,
			maxComponentConfigBytes,
		)
	}
	content, err := os.ReadFile(path)
	if err != nil {
		return nil, false, fmt.Errorf(
			"scaffold: read %s: %w",
			relative,
			err,
		)
	}
	return content, true, nil
}

func readComponentManifests(
	ctx context.Context,
	root string,
) ([]applicationComponent, error) {
	directory := filepath.Join(root, ".keelith", "components")
	info, err := os.Lstat(directory)
	switch {
	case errors.Is(err, os.ErrNotExist):
		return nil, nil
	case err != nil:
		return nil, fmt.Errorf("scaffold: inspect component declarations: %w", err)
	case info.Mode()&os.ModeSymlink != 0 || !info.IsDir():
		return nil, fmt.Errorf(
			"%w: .keelith/components is not a regular directory",
			ErrConflict,
		)
	}
	entries, err := os.ReadDir(directory)
	if err != nil {
		return nil, fmt.Errorf("scaffold: read component declarations: %w", err)
	}
	if len(entries) > maxComponentManifests {
		return nil, fmt.Errorf(
			"%w: component declaration count exceeds %d",
			ErrConflict,
			maxComponentManifests,
		)
	}
	components := make([]applicationComponent, 0, len(entries))
	seenNames := make(map[string]struct{}, len(entries))
	seenAccessors := make(map[string]string, len(entries))
	totalBytes := int64(0)
	for _, entry := range entries {
		if cause := context.Cause(ctx); cause != nil {
			return nil, cause
		}
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".json" {
			return nil, fmt.Errorf(
				"%w: component declaration %q is unsupported",
				ErrConflict,
				entry.Name(),
			)
		}
		relative := filepath.ToSlash(filepath.Join(
			".keelith",
			"components",
			entry.Name(),
		))
		path, err := safeAddOutputPath(root, relative, false)
		if err != nil {
			return nil, err
		}
		info, err := os.Lstat(path)
		if err != nil ||
			info.Mode()&os.ModeSymlink != 0 ||
			!info.Mode().IsRegular() {
			return nil, fmt.Errorf(
				"%w: %s is not a regular file",
				ErrConflict,
				relative,
			)
		}
		totalBytes += info.Size()
		if info.Size() <= 0 || totalBytes > maxComponentBytes {
			return nil, fmt.Errorf(
				"%w: component declarations exceed byte budget",
				ErrConflict,
			)
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("scaffold: read %s: %w", relative, err)
		}
		var manifest componentManifest
		decoder := json.NewDecoder(bytes.NewReader(content))
		decoder.DisallowUnknownFields()
		if err := decoder.Decode(&manifest); err != nil {
			return nil, fmt.Errorf(
				"%w: decode %s: %w",
				ErrConflict,
				relative,
				err,
			)
		}
		var extra any
		if err := decoder.Decode(&extra); !errors.Is(err, io.EOF) {
			return nil, fmt.Errorf(
				"%w: %s contains trailing JSON",
				ErrConflict,
				relative,
			)
		}
		if err := validateComponentManifest(root, entry.Name(), manifest); err != nil {
			return nil, err
		}
		if _, duplicate := seenNames[manifest.Name]; duplicate {
			return nil, fmt.Errorf(
				"%w: duplicate component name %q",
				ErrConflict,
				manifest.Name,
			)
		}
		seenNames[manifest.Name] = struct{}{}
		accessor := componentAccessor(manifest.Kind, manifest.Name)
		if owner, duplicate := seenAccessors[accessor]; duplicate {
			return nil, fmt.Errorf(
				"%w: components %q and %q share accessor %q",
				ErrConflict,
				owner,
				manifest.Name,
				accessor,
			)
		}
		seenAccessors[accessor] = manifest.Name
		components = append(components, applicationComponent{
			manifest: manifest,
			accessor: accessor,
		})
	}
	if err := validateComponentReferences(components); err != nil {
		return nil, err
	}
	sort.Slice(components, func(first, second int) bool {
		firstPriority := componentPriority(components[first].manifest.Kind)
		secondPriority := componentPriority(components[second].manifest.Kind)
		if firstPriority != secondPriority {
			return firstPriority < secondPriority
		}
		return components[first].manifest.Name < components[second].manifest.Name
	})
	return components, nil
}

func validateComponentManifest(
	root string,
	filename string,
	manifest componentManifest,
) error {
	if manifest.SchemaVersion != componentManifestVersion ||
		!supportedComponentKind(manifest.Kind) ||
		!validComponentName(manifest.Name) ||
		filename != manifest.Name+".json" {
		return fmt.Errorf(
			"%w: component declaration %q has invalid identity",
			ErrConflict,
			filename,
		)
	}
	if err := validateComponentManifestShape(manifest); err != nil {
		return err
	}
	expected := "config/components/" + manifest.Name + ".yaml"
	if manifest.Config != expected {
		return fmt.Errorf(
			"%w: component %q config path must be %q",
			ErrConflict,
			manifest.Name,
			expected,
		)
	}
	configPath, err := safeAddOutputPath(root, manifest.Config, false)
	if err != nil {
		return err
	}
	if _, exists, err := readRegularComponentFile(
		configPath,
		manifest.Config,
	); err != nil {
		return err
	} else if !exists {
		return fmt.Errorf(
			"%w: component %q config is missing",
			ErrConflict,
			manifest.Name,
		)
	}
	return nil
}

func supportedComponentKind(kind string) bool {
	switch kind {
	case "redis", "sql", "kafka-producer", "kafka-consumer", "cron-job",
		"job-ownership",
		"outbox", "inbox", "outbox-maintenance", "inbox-maintenance",
		"saga", "idempotency", "distributed-rate-limit":
		return true
	default:
		return false
	}
}

func validateComponentManifestShape(manifest componentManifest) error {
	fail := func() error {
		return fmt.Errorf(
			"%w: component %q has invalid dependency shape",
			ErrConflict,
			manifest.Name,
		)
	}
	switch manifest.Kind {
	case "sql":
		if (manifest.Driver != "" &&
			manifest.Driver != "mysql" &&
			manifest.Driver != "postgres") ||
			manifest.SQL != "" ||
			manifest.KafkaProducer != "" ||
			manifest.KafkaConsumer != "" ||
			manifest.Outbox != "" ||
			manifest.Inbox != "" ||
			manifest.CronJob != "" ||
			manifest.Redis != "" {
			return fail()
		}
	case "outbox":
		if (manifest.Driver != "mysql" && manifest.Driver != "postgres") ||
			!validComponentName(manifest.SQL) ||
			!validComponentName(manifest.KafkaProducer) ||
			manifest.KafkaConsumer != "" ||
			manifest.Outbox != "" ||
			manifest.Inbox != "" ||
			manifest.CronJob != "" ||
			manifest.Redis != "" {
			return fail()
		}
	case "inbox":
		if (manifest.Driver != "mysql" && manifest.Driver != "postgres") ||
			!validComponentName(manifest.SQL) ||
			!validComponentName(manifest.KafkaConsumer) ||
			manifest.KafkaProducer != "" ||
			manifest.Outbox != "" ||
			manifest.Inbox != "" ||
			manifest.CronJob != "" ||
			manifest.Redis != "" {
			return fail()
		}
	case "outbox-maintenance":
		if !validComponentName(manifest.Outbox) ||
			!validComponentName(manifest.CronJob) ||
			(manifest.Driver != "" &&
				manifest.Driver != "mysql" &&
				manifest.Driver != "postgres") ||
			manifest.SQL != "" ||
			manifest.KafkaProducer != "" ||
			manifest.KafkaConsumer != "" ||
			manifest.Inbox != "" ||
			manifest.Redis != "" {
			return fail()
		}
	case "inbox-maintenance":
		if !validComponentName(manifest.Inbox) ||
			!validComponentName(manifest.CronJob) ||
			(manifest.Driver != "" &&
				manifest.Driver != "mysql" &&
				manifest.Driver != "postgres") ||
			manifest.SQL != "" ||
			manifest.KafkaProducer != "" ||
			manifest.KafkaConsumer != "" ||
			manifest.Outbox != "" ||
			manifest.Redis != "" {
			return fail()
		}
	case "saga":
		if (manifest.Driver != "mysql" && manifest.Driver != "postgres") ||
			!validComponentName(manifest.SQL) ||
			!validComponentName(manifest.Redis) ||
			manifest.KafkaProducer != "" ||
			manifest.KafkaConsumer != "" ||
			manifest.Outbox != "" ||
			manifest.Inbox != "" ||
			manifest.CronJob != "" {
			return fail()
		}
	case "idempotency", "distributed-rate-limit":
		if !validComponentName(manifest.Redis) ||
			manifest.Driver != "" ||
			manifest.SQL != "" ||
			manifest.KafkaProducer != "" ||
			manifest.KafkaConsumer != "" ||
			manifest.Outbox != "" ||
			manifest.Inbox != "" ||
			manifest.CronJob != "" {
			return fail()
		}
	case "job-ownership":
		if !validComponentName(manifest.CronJob) ||
			manifest.SQL != "" ||
			manifest.KafkaProducer != "" ||
			manifest.KafkaConsumer != "" ||
			manifest.Outbox != "" ||
			manifest.Inbox != "" {
			return fail()
		}
		switch manifest.Driver {
		case "redis":
			if !validComponentName(manifest.Redis) {
				return fail()
			}
		case "kubernetes":
			if manifest.Redis != "" {
				return fail()
			}
		default:
			return fail()
		}
	default:
		if manifest.Driver != "" ||
			manifest.SQL != "" ||
			manifest.KafkaProducer != "" ||
			manifest.KafkaConsumer != "" ||
			manifest.Outbox != "" ||
			manifest.Inbox != "" ||
			manifest.CronJob != "" ||
			manifest.Redis != "" {
			return fail()
		}
	}
	return nil
}

func validateComponentReferences(
	components []applicationComponent,
) error {
	byName := make(
		map[string]componentManifest,
		len(components),
	)
	for _, component := range components {
		byName[component.manifest.Name] = component.manifest
	}
	decoratedConsumers := make(map[string]string)
	decoratedJobs := make(map[string]string)
	ownedJobs := make(map[string]string)
	idempotencyOwner := ""
	distributedRateLimitOwner := ""
	for _, component := range components {
		manifest := component.manifest
		switch manifest.Kind {
		case "outbox":
			sqlDependency, sqlExists := byName[manifest.SQL]
			producer, producerExists := byName[manifest.KafkaProducer]
			if !sqlExists ||
				sqlDependency.Kind != "sql" ||
				componentSQLDialect(sqlDependency) != manifest.Driver ||
				!producerExists ||
				producer.Kind != "kafka-producer" {
				return fmt.Errorf(
					"%w: Outbox %q requires %s SQL %q and Kafka producer %q",
					ErrConflict,
					manifest.Name,
					manifest.Driver,
					manifest.SQL,
					manifest.KafkaProducer,
				)
			}
		case "inbox":
			sqlDependency, sqlExists := byName[manifest.SQL]
			consumer, consumerExists := byName[manifest.KafkaConsumer]
			if !sqlExists ||
				sqlDependency.Kind != "sql" ||
				componentSQLDialect(sqlDependency) != manifest.Driver ||
				!consumerExists ||
				consumer.Kind != "kafka-consumer" {
				return fmt.Errorf(
					"%w: Inbox %q requires %s SQL %q and Kafka consumer %q",
					ErrConflict,
					manifest.Name,
					manifest.Driver,
					manifest.SQL,
					manifest.KafkaConsumer,
				)
			}
			if owner, duplicate := decoratedConsumers[manifest.KafkaConsumer]; duplicate {
				return fmt.Errorf(
					"%w: Inbox %q and %q decorate Kafka consumer %q",
					ErrConflict,
					owner,
					manifest.Name,
					manifest.KafkaConsumer,
				)
			}
			decoratedConsumers[manifest.KafkaConsumer] = manifest.Name
		case "outbox-maintenance":
			outbox, outboxExists := byName[manifest.Outbox]
			job, jobExists := byName[manifest.CronJob]
			if !outboxExists ||
				outbox.Kind != "outbox" ||
				(manifest.Driver != "" &&
					manifest.Driver != outbox.Driver) ||
				!jobExists ||
				job.Kind != "cron-job" {
				return fmt.Errorf(
					"%w: Outbox maintenance %q requires Outbox %q and Cron Job %q",
					ErrConflict,
					manifest.Name,
					manifest.Outbox,
					manifest.CronJob,
				)
			}
			if owner, duplicate := decoratedJobs[manifest.CronJob]; duplicate {
				return fmt.Errorf(
					"%w: Outbox maintenance %q and %q decorate Cron Job %q",
					ErrConflict,
					owner,
					manifest.Name,
					manifest.CronJob,
				)
			}
			decoratedJobs[manifest.CronJob] = manifest.Name
		case "inbox-maintenance":
			inbox, inboxExists := byName[manifest.Inbox]
			job, jobExists := byName[manifest.CronJob]
			if !inboxExists ||
				inbox.Kind != "inbox" ||
				(manifest.Driver != "" &&
					manifest.Driver != inbox.Driver) ||
				!jobExists ||
				job.Kind != "cron-job" {
				return fmt.Errorf(
					"%w: Inbox maintenance %q requires Inbox %q and Cron Job %q",
					ErrConflict,
					manifest.Name,
					manifest.Inbox,
					manifest.CronJob,
				)
			}
			if owner, duplicate := decoratedJobs[manifest.CronJob]; duplicate {
				return fmt.Errorf(
					"%w: maintenance %q and %q decorate Cron Job %q",
					ErrConflict,
					owner,
					manifest.Name,
					manifest.CronJob,
				)
			}
			decoratedJobs[manifest.CronJob] = manifest.Name
		case "saga":
			sqlDependency, sqlExists := byName[manifest.SQL]
			redisDependency, redisExists := byName[manifest.Redis]
			if !sqlExists ||
				sqlDependency.Kind != "sql" ||
				componentSQLDialect(sqlDependency) != manifest.Driver ||
				!redisExists ||
				redisDependency.Kind != "redis" {
				return fmt.Errorf(
					"%w: Saga %q requires %s SQL %q and Redis %q",
					ErrConflict,
					manifest.Name,
					manifest.Driver,
					manifest.SQL,
					manifest.Redis,
				)
			}
		case "idempotency":
			redisDependency, redisExists := byName[manifest.Redis]
			if !redisExists || redisDependency.Kind != "redis" {
				return fmt.Errorf(
					"%w: idempotency %q requires Redis %q",
					ErrConflict,
					manifest.Name,
					manifest.Redis,
				)
			}
			if idempotencyOwner != "" {
				return fmt.Errorf(
					"%w: idempotency components %q and %q overlap",
					ErrConflict,
					idempotencyOwner,
					manifest.Name,
				)
			}
			idempotencyOwner = manifest.Name
		case "distributed-rate-limit":
			redisDependency, redisExists := byName[manifest.Redis]
			if !redisExists || redisDependency.Kind != "redis" {
				return fmt.Errorf(
					"%w: distributed rate limit %q requires Redis %q",
					ErrConflict,
					manifest.Name,
					manifest.Redis,
				)
			}
			if distributedRateLimitOwner != "" {
				return fmt.Errorf(
					"%w: distributed rate-limit components %q and %q overlap",
					ErrConflict,
					distributedRateLimitOwner,
					manifest.Name,
				)
			}
			distributedRateLimitOwner = manifest.Name
		case "job-ownership":
			job, jobExists := byName[manifest.CronJob]
			if !jobExists || job.Kind != "cron-job" {
				return fmt.Errorf(
					"%w: Job ownership %q requires Cron Job %q",
					ErrConflict,
					manifest.Name,
					manifest.CronJob,
				)
			}
			if manifest.Driver == "redis" {
				redisDependency, redisExists := byName[manifest.Redis]
				if !redisExists || redisDependency.Kind != "redis" {
					return fmt.Errorf(
						"%w: Redis Job ownership %q requires Redis %q",
						ErrConflict,
						manifest.Name,
						manifest.Redis,
					)
				}
			}
			if owner, duplicate := ownedJobs[manifest.CronJob]; duplicate {
				return fmt.Errorf(
					"%w: Job ownership %q and %q overlap Cron Job %q",
					ErrConflict,
					owner,
					manifest.Name,
					manifest.CronJob,
				)
			}
			ownedJobs[manifest.CronJob] = manifest.Name
		}
	}
	return nil
}

func componentPriority(kind string) int {
	switch kind {
	case "outbox", "inbox", "saga", "idempotency", "distributed-rate-limit",
		"job-ownership":
		return 1
	case "outbox-maintenance", "inbox-maintenance":
		return 2
	default:
		return 0
	}
}

func exportedComponentName(name string) string {
	var result strings.Builder
	upper := true
	for _, r := range name {
		if r == '-' {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		result.WriteRune(r)
	}
	return result.String()
}

